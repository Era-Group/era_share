def describe(code, fallback_description=None):
    """Return a user-facing (reason, action) pair for a BWATECH status code."""
    entry = BWATECH_STATUS_CODES.get(str(code or "").strip())
    if entry:
        return entry
    reason = fallback_description or "خطأ غير معروف من بواتك."
    return (reason, "أرسل رقم التتبع (correlationID) لبواتك للمراجعة.")
